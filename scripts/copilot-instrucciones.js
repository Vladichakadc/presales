#!/usr/bin/env node
'use strict';
// Las copias para GitHub Copilot de siete skills (2026-10-02).
//
// La extensión Claude Skills Manager las generó el 2026-08-17: `.github/instructions/<skill>.instructions.md`
// lleva la descripción y el cuerpo del `SKILL.md` de la skill, con su `applyTo`, y
// `.github/copilot-instructions.md` las lista con esa misma descripción. Esa extensión no corre
// aquí, así que una skill que cambia deja su copia diciendo lo anterior, y nada lo nota: el
// 2026-10-02 la auditoría de prompts cambió tres de las siete.
//
// Este script hace lo que hacía la extensión, con el mismo formato, y `--comprobar` dice qué copia
// no coincide con su skill sin escribir nada; `test/copilot-instrucciones.test.js` lo exige en
// `npm run verificar`. Qué skills tienen copia y con qué `applyTo` lo deciden las copias que ya
// existen: este script no crea ni retira ninguna.
//
//   node scripts/copilot-instrucciones.js              # regenera las que no coinciden
//   node scripts/copilot-instrucciones.js --comprobar  # sale con 1 si alguna no coincide
const fs = require('fs');
const path = require('path');

const RAIZ = path.join(__dirname, '..');
const DIR_COPIAS = path.join(RAIZ, '.github', 'instructions');
const INDICE = path.join(RAIZ, '.github', 'copilot-instructions.md');
const DIR_SKILLS = path.join(RAIZ, '.claude', 'skills');
const MARCA = [
  '<!-- Copilot Instruction Telemetry: This file was auto-generated by Claude Skills Manager -->',
  '<!-- If this instruction was helpful, please report it to help improve adoption metrics -->',
];

const sinCr = (t) => t.replace(/\r\n/g, '\n');

// La cabecera YAML y el cuerpo de un archivo que empieza por `---`.
function partir(texto, donde) {
  const m = sinCr(texto).match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error(`${donde}: no empieza por una cabecera --- … ---`);
  return { cabecera: m[1], cuerpo: m[2] };
}

// La descripción de la cabecera de una skill: en una línea, con comillas o sin ellas, o en bloque.
function descripcion(cabecera, donde) {
  const lineas = cabecera.split('\n');
  const i = lineas.findIndex((l) => /^description:/.test(l));
  if (i < 0) throw new Error(`${donde}: la cabecera no trae description`);
  const valor = lineas[i].slice('description:'.length).trim();
  if (/^[>|]-?$/.test(valor)) {
    const bloque = [];
    for (const l of lineas.slice(i + 1)) {
      if (!/^\s/.test(l) && l !== '') break;
      bloque.push(l.trim());
    }
    return bloque.join(valor.startsWith('>') ? ' ' : '\n').replace(/\s+$/, '');
  }
  if (valor.startsWith('"')) return JSON.parse(valor);
  if (valor.startsWith("'")) return valor.slice(1, -1).replace(/''/g, "'");
  return valor;
}

// Lo que tiene que decir la copia de una skill, sin la fecha de despliegue.
function copiaEsperada(nombre, copiaActual) {
  const donde = `.claude/skills/${nombre}/SKILL.md`;
  const archivo = path.join(DIR_SKILLS, nombre, 'SKILL.md');
  if (!fs.existsSync(archivo)) throw new Error(`${donde} no existe: la copia de Copilot se quedó sin skill`);
  const skill = partir(fs.readFileSync(archivo, 'utf8'), donde);
  const copia = partir(copiaActual, `.github/instructions/${nombre}.instructions.md`);
  const applyTo = copia.cabecera.match(/^applyTo:[^\n]*(?:\n(?:  - )[^\n]*)*/m);
  if (!applyTo) throw new Error(`.github/instructions/${nombre}.instructions.md: la cabecera no trae applyTo`);
  const [primera, ...resto] = skill.cuerpo.split('\n');
  const cuerpo = [primera, `# ${nombre}`, '', ...MARCA, '', ...resto].join('\n');
  return {
    descripcion: descripcion(skill.cabecera, donde),
    cabecera: [`name: ${JSON.stringify(nombre)}`, `description: ${JSON.stringify(descripcion(skill.cabecera, donde))}`, applyTo[0]].join('\n'),
    cuerpo,
  };
}

// La fila del índice de una skill, con sus globs y su descripción.
function filaIndice(nombre, globs, desc) {
  return `| ${nombre} | \`${globs}\` — ${desc} |`;
}

// Cada copia y la fila del índice, comparadas con lo que dice hoy su skill.
function revisar() {
  const nombres = fs.readdirSync(DIR_COPIAS).filter((f) => f.endsWith('.instructions.md')).map((f) => f.replace(/\.instructions\.md$/, '')).sort();
  const indice = sinCr(fs.readFileSync(INDICE, 'utf8'));
  const resultado = { nombres, cambios: [], indice };
  let nuevoIndice = indice;
  for (const nombre of nombres) {
    const ruta = path.join(DIR_COPIAS, `${nombre}.instructions.md`);
    const actual = sinCr(fs.readFileSync(ruta, 'utf8'));
    const esperada = copiaEsperada(nombre, actual);
    const { cabecera, cuerpo } = partir(actual, ruta);
    const sinFecha = cabecera.replace(/\ndeployedAt:[^\n]*/, '');
    if (sinFecha !== esperada.cabecera || cuerpo !== esperada.cuerpo) {
      const fecha = new Date().toISOString();
      resultado.cambios.push({
        nombre,
        ruta,
        texto: `---\n${esperada.cabecera}\ndeployedAt: ${JSON.stringify(fecha)}\n---\n${esperada.cuerpo}`,
      });
    }
    const fila = nuevoIndice.match(new RegExp(`^\\| ${nombre} \\| \`([^\`]*)\` — .*\\|$`, 'm'));
    if (!fila) throw new Error(`.github/copilot-instructions.md no tiene la fila de ${nombre}`);
    nuevoIndice = nuevoIndice.replace(fila[0], filaIndice(nombre, fila[1], esperada.descripcion));
  }
  resultado.nuevoIndice = nuevoIndice;
  return resultado;
}

if (require.main === module) {
  const r = revisar();
  const indiceCambia = r.nuevoIndice !== r.indice;
  if (process.argv.includes('--comprobar')) {
    for (const c of r.cambios) console.error(`No coincide con su skill: ${path.relative(RAIZ, c.ruta)}`);
    if (indiceCambia) console.error('No coincide con las skills: .github/copilot-instructions.md');
    if (r.cambios.length || indiceCambia) {
      console.error('Para regenerarlas: node scripts/copilot-instrucciones.js');
      process.exit(1);
    }
    console.log(`Las ${r.nombres.length} copias de Copilot coinciden con sus skills.`);
  } else {
    for (const c of r.cambios) {
      fs.writeFileSync(c.ruta, c.texto);
      console.log(`Regenerada: ${path.relative(RAIZ, c.ruta)}`);
    }
    if (indiceCambia) {
      fs.writeFileSync(INDICE, r.nuevoIndice);
      console.log('Regenerado: .github/copilot-instructions.md');
    }
    if (!r.cambios.length && !indiceCambia) console.log('Nada que regenerar.');
  }
}

module.exports = { revisar, copiaEsperada, descripcion, partir };
